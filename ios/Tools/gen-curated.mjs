// Bake the PWA's Trusted Programs (CURATED) into Swift, each keyword already resolved to a library id by
// the PWA's own resolveExercise(keyword, true) running on the real exercise list -- parity by construction,
// the same idea as gen-pwa-tables.mjs. Library-only (custom exercises never count here).
// node Tools/gen-curated.mjs > Jacked/Data/Curated.swift   (PW_EXE=<chrome> if the default build is missing)
import { createRequire } from 'module'; import { spawn } from 'child_process'; import fs from 'fs';
const require = createRequire('/home/roni/agent/projects/Jacked/tests/e2e/');
const { chromium } = require('playwright');
const acct = JSON.parse(fs.readFileSync('/home/roni/agent/config/jacked-ios-dev-test-account.json'));
const PORT = 8792;
const srv = spawn('python3', ['-m', 'http.server', String(PORT), '--bind', '127.0.0.1', '--directory', '/home/roni/agent/projects/Jacked/jacked-pwa'], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 800));
const b = await chromium.launch({ executablePath: process.env.PW_EXE || chromium.executablePath(), args: ['--no-sandbox'] });
try {
  const p = await (await b.newContext({ serviceWorkers: 'block' })).newPage();
  await p.goto(`http://127.0.0.1:${PORT}/index.html`);
  await p.waitForSelector('#loginUser', { state: 'visible', timeout: 15000 });
  await p.fill('#loginUser', '@' + acct.username); await p.fill('#loginPass', acct.password);
  await p.click('#ob0 button[type=submit]');
  await p.waitForFunction(() => (JSON.parse(localStorage.getItem('jk_hist') || '[]')).length > 0, null, { timeout: 20000 });
  await p.evaluate(async () => { loadDB(); for (let j = 0; j < 100 && !dbLoaded; j++) await new Promise(r => setTimeout(r, 100)); });
  const progs = await p.evaluate(() => { if (!dbLoaded) throw new Error('exercise list never loaded');
    return CURATED.map(pr => ({ name: pr.name, source: pr.source, desc: pr.desc,
      routines: pr.routines.map(r => ({ name: r.name, ids: r.exercises.map(k => resolveExercise(k, true)).filter(Boolean) })) })); });
  const q = s => JSON.stringify(s);
  let out = `// GENERATED by Tools/gen-curated.mjs from jacked-pwa/index.html CURATED + resolveExercise. Do not edit by hand.\n\n`;
  out += `/// The Trusted Programs list (index.html CURATED), keywords already resolved to library ids.\nenum Curated {\n`;
  out += `    struct Routine { let name: String; let ids: [String] }\n    struct Program { let name: String; let source: String; let desc: String; let routines: [Routine] }\n`;
  out += `    static let programs: [Program] = [\n`;
  for (const pr of progs) {
    out += `        Program(name: ${q(pr.name)}, source: ${q(pr.source)}, desc: ${q(pr.desc)}, routines: [\n`;
    for (const r of pr.routines) out += `            Routine(name: ${q(r.name)}, ids: ${q(r.ids)}),\n`;
    out += `        ]),\n`;
  }
  out += `    ]\n}\n`;
  process.stdout.write(out);
} finally { await b.close(); srv.kill(); }
