// Writes ios/Jacked/Data/BadgeTables.swift from the PWA's OWN badge constants in jacked-pwa/index.html
// (no hand copy): the standard exercise ids per badge and every sourced tier table (bench GOODLIFT,
// McCulloch, squat / OHP / pull-up / push-up standards, WMA mile age factors, cardio times).
// Re-run whenever index.html changes one of them.   node ios/Tools/gen-badge-tables.mjs
import fs from 'node:fs'; import vm from 'node:vm'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const html = fs.readFileSync(path.join(here, '../../jacked-pwa/index.html'), 'utf8');
function constSrc(name) {
  const at = html.search(new RegExp(`^const ${name}\\s*=`, 'm')); if (at < 0) throw new Error('not found ' + name);
  let i = html.indexOf('=', at) + 1, depth = 0, started = false, q = null;
  for (; i < html.length; i++) {
    const c = html[i];
    if (q) { if (c === '\\') { i++; continue; } if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') { q = c; continue; }
    if (c === '/' && html[i + 1] === '/') { i = html.indexOf('\n', i) - 1; continue; }
    if ('([{'.includes(c)) { depth++; started = true; } else if (')]}'.includes(c)) depth--;
    else if (c === ';' && started && depth === 0) break;
    if (c === '\n' && started && depth === 0) break;
  }
  return html.slice(at, i) + ';';
}
const names = ['BADGE_STD', 'GL_BENCH', 'BENCH_POINTS', 'MCCULLOCH', 'BENCH_FALLBACK_LB', 'SQUAT_STD', 'OHP_STD', 'REP_STD_AGES', 'PULLUP_STD', 'PUSHUP_STD',
  'CARDIO_STD', 'WMA_MILE', 'BADGE_DB_BONUS'];
const ctx = {}; vm.createContext(ctx);
vm.runInContext(names.map(constSrc).join('\n') + '\nglobalThis.__t={' + names.join(',') + ',BADGE_SMITH_CUT};', ctx);
const t = JSON.parse(JSON.stringify(ctx.__t)), q = s => JSON.stringify(String(s));
const num = a => '[' + a.map(x => Array.isArray(x) ? num(x) : String(x)).join(', ') + ']';
const sexD = (o, f) => `["male": ${f(o.male)}, "female": ${f(o.female)}]`;
const rep = o => `RepStd(bw: ${num(o.bw)}, rows: ${num(o.rows)}, age: ${num(o.age)})`;
const out = `// GENERATED by ios/Tools/gen-badge-tables.mjs from jacked-pwa/index.html. Do not edit by hand.
import Foundation

struct RepStd { let bw: [Double]; let rows: [[Double]]; let age: [[Double]] }

enum BadgeTables {
    static let BADGE_STD: [String: [String]] = [${Object.entries(t.BADGE_STD).map(([k, v]) => `${q(k)}: [${v.map(q).join(', ')}]`).join(', ')}]
    static let GL_BENCH: [String: [Double]] = ${sexD(t.GL_BENCH, num)}
    static let BENCH_POINTS: [Double] = ${num(t.BENCH_POINTS)}
    static let MCCULLOCH: [Double] = ${num(t.MCCULLOCH)}
    static let BENCH_FALLBACK_LB: [Double] = ${num(t.BENCH_FALLBACK_LB)}
    static let SQUAT_STD: [String: [[Double]]] = ${sexD(t.SQUAT_STD, num)}
    static let OHP_STD: [String: [[Double]]] = ${sexD(t.OHP_STD, num)}
    static let REP_STD_AGES: [Double] = ${num(t.REP_STD_AGES)}
    static let PULLUP_STD: [String: RepStd] = ${sexD(t.PULLUP_STD, rep)}
    static let PUSHUP_STD: [String: RepStd] = ${sexD(t.PUSHUP_STD, rep)}
    static let CARDIO_STD: [String: [Double]] = ${sexD(t.CARDIO_STD, num)}
    static let WMA_MILE: [String: [Double]] = ${sexD(t.WMA_MILE, num)}
    static let BADGE_DB_BONUS = ${t.BADGE_DB_BONUS}, BADGE_SMITH_CUT = ${t.BADGE_SMITH_CUT}
}
`;
fs.writeFileSync(path.join(here, '../Jacked/Data/BadgeTables.swift'), out);
console.log('wrote BadgeTables.swift', Object.keys(t.BADGE_STD).length, 'badge keys');
