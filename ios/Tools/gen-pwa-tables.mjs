// Writes ios/Jacked/Data/PWATables.swift from the PWA's OWN constants in jacked-pwa/index.html
// (no hand copy): Single/Both lists, bodyweight exceptions, equipment fixes, timed holds and the
// built-in warm-ups/machines/runs. Re-run whenever index.html changes one of them.
//   node ios/Tools/gen-pwa-tables.mjs
import fs from 'node:fs'; import vm from 'node:vm'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const html = fs.readFileSync(path.join(here, '../../jacked-pwa/index.html'), 'utf8');
function constSrc(name) {   // `const NAME = ...;` up to the matching close of its first bracket
  const at = html.search(new RegExp(`^const ${name}\\s*=`, 'm')); if (at < 0) throw new Error('not found ' + name);
  let i = html.indexOf('=', at) + 1, depth = 0, started = false, q = null;
  for (; i < html.length; i++) {
    const c = html[i];
    if (q) { if (c === '\\') { i++; continue; } if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') { q = c; continue; }
    if ('([{'.includes(c)) { depth++; started = true; } else if (')]}'.includes(c)) depth--;
    else if (c === ';' && started && depth === 0) break;
    if (c === '\n' && started && depth === 0) break;
  }
  return html.slice(at, i) + ';';
}
const names = ['SINGLE_DEFAULT_IDS', 'SINGLE_BOTH_IDS', 'DOUBLE_VOL_IDS', 'NOT_BW_IDS', 'EQUIP_FIX', 'EQUIP_TAG', 'TIMED_HOLDS', 'WARMUPS', 'MACHINES', 'RUNS'];
const ctx = {}; vm.createContext(ctx);
vm.runInContext(names.map(constSrc).join('\n') + '\nglobalThis.__t={' + names.join(',') + '};', ctx);
const t = ctx.__t, q = s => JSON.stringify(String(s));
const set = n => `    static let ${n}: Set<String> = [${[...t[n]].sort().map(q).join(', ')}]`;
const dict = n => `    static let ${n}: [String: String] = [${Object.entries(t[n]).map(([k, v]) => `${q(k)}: ${q(v)}`).join(', ')}]`;
const ex = e => `        CatalogExercise(id: ${q(e.id)}, name: ${q(e.name)}, muscle: ${q(e.muscle || '')}, equip: ${q(e.equip || '')}, tracking: ${q(e.tracking || 'weight_reps')}, assist: ${!!e.assist}, image: ${e.images && e.images.length ? q(e.images[0]) : 'nil'}, custom: ${!!e._c})`;
const out = `// GENERATED by ios/Tools/gen-pwa-tables.mjs from jacked-pwa/index.html. Do not edit by hand.
import Foundation

enum PWATables {
${['SINGLE_DEFAULT_IDS', 'SINGLE_BOTH_IDS', 'DOUBLE_VOL_IDS', 'NOT_BW_IDS', 'TIMED_HOLDS'].map(set).join('\n')}
${['EQUIP_FIX', 'EQUIP_TAG'].map(dict).join('\n')}
    /// WARMUPS, MACHINES and RUNS, in that order.
    static let builtIns: [CatalogExercise] = [
${[...t.WARMUPS, ...t.MACHINES, ...t.RUNS].map(ex).join(',\n')}
    ]
}
`;
fs.writeFileSync(path.join(here, '../Jacked/Data/PWATables.swift'), out);
console.log('wrote PWATables.swift', [...t.SINGLE_BOTH_IDS].length, 'single/both,', t.WARMUPS.length + t.MACHINES.length + t.RUNS.length, 'built-ins');
